#pragma once

#include <windows.h>

//
// 全屏置顶覆盖层反制（反锁屏勒索 / 假 UAC / 假登录框 / 覆盖层攻击）。
//
// 这是**引擎侧的主动反制**，跑在引擎进程里（不是被注入进程里）——
// 桌面上只该有一个执行者，否则每个被注入进程都会去抢同一批窗口。
//
// 触发判据（**全部满足**才算“覆盖层”，见 MatchesOverlaySignature）：
//   · 顶层窗口、可见、未最小化；
//   · 带 WS_EX_TOPMOST（置顶）；
//   · 无 WS_CAPTION、无 WS_SYSMENU（无边框 —— 锁屏勒索的典型签名）；
//   · **盖住任务栏那种全屏**（覆盖整块显示器 rcMonitor，含任务栏条带）——
//     普通最大化窗口只覆盖工作区 rcWork，**不算**，天然被排除；
//   · 不属于本进程；不是外壳/系统窗口；目标进程完整性级别不高于本进程。
//
// ------------------------------------------------------------------
// 反制五级升级（与 tools/overlay_ladder_probe.cpp 的实证一致）
// ------------------------------------------------------------------
//   ① 最小化    ShowWindow(SW_MINIMIZE)                     可逆，最温和
//   ② 关闭      PostMessage(WM_CLOSE)                       让程序自己决定退不退
//   ③ 销毁窗口  隐藏父窗口 → SetParent → DestroyWindow(父)    强行拿走窗口
//   ④ 调用退出函数  远程线程调用目标进程的 ExitProcess         让进程走**正常退出**路径
//   ⑤ 暴力杀进程 TerminateProcess                            最后手段
//
// ⚠️ 只有上一级“没解决”才升级：
//    最小化后窗口若**重新出现**才关；关了还在才销毁；销毁了还在才 ④ ⑤。
//    因此普通窗口只会在第 ① 级被最小化（可恢复），不会走到 ④ ⑤。
//
// ⚠️ ③ 只拿走窗口、**不杀进程** —— 恶意程序可以重建窗口（这就是“反制没效果”），
//    所以 ④ ⑤ 才是对“杀不死”的窗口的最终手段。
//
// ★★ 升级进度按 **pid** 记账，不按 hwnd。
//    这是“窗口反制没效果”能走到 ④⑤ 的前提：③ 把窗口拿掉后，顽固程序会**重建
//    一个新窗口**（新 hwnd）。若按 hwnd 记账，旧条目被清、新条目 rungs=0，
//    阶梯永远卡在 ①，④⑤ 根本不可达 —— 正是用户反馈的场景。
//    改成按 pid 记账后，同一进程换多少个窗口，rungs 都连续累加；
//    条目只在**进程退出**或保留期到期时清理（窗口没了不清理）。
//
// ------------------------------------------------------------------
// 询问级别（ini: neutralize_overlay = 0 / 1 / 2）
// ------------------------------------------------------------------
//   0 = 关闭反制
//   1 = 开启，**不问**：每一级直接执行
//   2 = 开启，**弹窗询问**：每一级执行前先弹一个**居中置顶**的小窗问用户
//       （按钮：反制 / 跳过 / 不再询问）。
//
// ⚠️ 「用户点跳过」与「超时无人应答」**必须分开**（v59 修）：
//    · 用户**明确**点了「跳过」/ 按 Esc / 点 X → 尊重，本进程不再打扰；
//    · **超时**（没人作答）→ 只是"这次没结论"，**不能**当成"用户拒绝"。
//      覆盖层攻击的场景里弹窗**很可能**被覆盖层盖住 —— 用户根本没看见，
//      若按"跳过"处理，反制会在第一级就被**永久关掉**（这正是用户报的
//      "窗口反制好像用不了"的一种成因）。所以超时改为**有限重试**：
//      连续 kMaxAskTimeouts 次无应答才放弃，并把"怎么强制"写进日志。
//
// ⚠️ 询问**不阻塞主循环**：弹窗跑在独立线程上，Tick() 只查结果。
//    否则用户盯着弹窗不动时，事件排空与进程注入会整个停摆。
//
// ------------------------------------------------------------------
// 可诊断性（v59）—— 为什么必须有
// ------------------------------------------------------------------
//   旧版的判定是**布尔**的：一个窗口没被反制，日志里**一个字都没有**，
//   于是"没检测到 / 被排除了 / 反制失败"三种**完全不同**的结论在
//   r3shieldcore-console.log 里长得一模一样（铁律 75：日志里没有 != 没跑）。
//   现在：
//    · 判定拆成"结论 + 原因"（内部 OverlayVerdict）；
//    · 对"差一点命中"的窗口（无边框 + 可见 + 未最小化 + 至少盖满工作区）
//      打一行 `[sentinel] 差一点命中 ...`（每个 hwnd 一次）；
//    · 每 kHeartbeatMs 打一行心跳（扫描数 / 命中数 / 排除数 / 各级动作 / 询问）。
//   ⇒ "没反制"时，看一眼心跳就知道是"没扫到"还是"扫到但不满足签名"。
//
namespace R3ShieldCoreSentinel
{
	struct Stats
	{
		ULONG Ticks = 0;      // Tick() 调用次数
		ULONG Scans = 0;      // 实际扫描次数（节流后）
		ULONG Detected = 0;   // 累计判定为覆盖层
		ULONG Minimized = 0;  // 第 ① 级动作次数
		ULONG Closed = 0;     // 第 ② 级动作次数
		ULONG Destroyed = 0;  // 第 ③ 级动作次数
		ULONG ExitRequested = 0; // 第 ④ 级动作次数（调用退出函数）
		ULONG Terminated = 0; // 第 ⑤ 级动作次数（暴力杀进程）
		ULONG Asked = 0;      // 弹窗询问次数
		ULONG Declined = 0;   // 用户选择“跳过”（或连续超时后放弃）的次数
		ULONG AskTimeouts = 0;// ★ 询问超时次数（与 Declined 分开统计）
		ULONG NearMiss = 0;   // ★ "差一点命中"的窗口数（诊断用；口径见 IsNearMissCandidate）
		ULONG Skipped = 0;    // 命中特征但被排除（自身/外壳/高完整性/不可访问）
		ULONG LastHwnd = 0;   // 最近一次处理的目标窗口
		ULONG LastAction = 0; // 1=最小化 2=关闭 3=销毁 4=退出函数 5=杀进程
		ULONG LastResult = 0; // 1=成功 0=失败
	};

	//
	// 启动反制。
	//
	// level: 0=关；1=开（不问）；2=开（弹窗询问）。
	// askTimeoutMs: 询问弹窗的等待毫秒数（超时 = 跳过）。传 0 用默认值。
	//
	void Start(ULONG level, ULONG askTimeoutMs = 0) noexcept;
	void Stop() noexcept;
	bool IsEnabled() noexcept;
	ULONG Level() noexcept;

	// 主循环调用。内部按 kScanIntervalMs 节流；未启用时立即返回。
	// ★ 绝不阻塞：询问弹窗在别的线程上。
	void Tick() noexcept;

	Stats GetStats() noexcept;
}
